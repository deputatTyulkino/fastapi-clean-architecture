from datetime import timedelta

from app.core.config import get_settings

settings = get_settings()

broker_url = f"{settings.REDIS_DURABLE_URL}/0"
result_backend = f"{settings.REDIS_DURABLE_URL}/1"
# Разные БД Redis для брокера и backend — чтобы очередь задач
# и хранилище результатов не путались друг с другом.

task_serializer = "json"
result_serializer = "json"
accept_content = ["json"]
# Явно фиксируем JSON, а не дефолтный pickle.
# Pickle умеет сериализовать произвольные объекты Python, но это
# уязвимость: если в очередь попадёт злонамеренное сообщение,
# unpickle может выполнить произвольный код при десериализации.
# JSON безопасен и достаточен — мы передаём в тасках только
# примитивы (id, списки, строки), а не живые объекты.

timezone = "UTC"
enable_utc = True
# Хранить и планировать всё в UTC — стандартная практика,
# избавляет от головной боли с переходом на летнее время
# и с серверами в разных таймзонах.

task_acks_late = True
# По умолчанию Celery подтверждает (ack) получение таски ДО её
# выполнения. Если воркер упадёт посреди выполнения — таска
# потеряется навсегда. acks_late=True откладывает ack до
# успешного завершения: если воркер умрёт — брокер отдаст
# таску другому воркеру.

task_reject_on_worker_lost = True
# Дополняет предыдущее: если воркер убит посреди выполнения
# (а не просто упал), таска явно возвращается в очередь,
# а не зависает в неопределённом статусе.

task_time_limit = 30
task_soft_time_limit = 20
# Soft limit кидает исключение SoftTimeLimitExceeded внутри
# таски — можно поймать и красиво завершиться (закрыть сессию
# БД, залогировать). Hard limit жёстко убивает процесс воркера,
# если soft не сработал. Оба меньше интервала beat (15 сек),
# чтобы зависшая таска не накапливалась пачками.

worker_prefetch_multiplier = 1
# Сколько задач воркер резервирует себе из очереди заранее.
# Дефолт 4 — хорош для множества мелких быстрых тасок, но плохо
# сочетается с acks_late: воркер может "разобрать" себе несколько
# тяжёлых тасок, а другие воркеры будут простаивать. Для тасок
# с ощутимой длительностью (у нас — обращение к БД) ставим 1:
# воркер берёт следующую задачу, только закончив предыдущую.

worker_max_tasks_per_child = 200
# Воркер перезапускает дочерний процесс после N выполненных
# тасок. Защита от постепенных утечек памяти (в том числе
# от твоего event loop в отдельном потоке — на всякий случай,
# если там что-то накапливается).

broker_connection_retry_on_startup = True
# Если Redis/RabbitMQ ещё не поднялся к моменту старта воркера
# (частый кейс в docker-compose с несколькими сервисами) —
# ретраить подключение, а не падать сразу.

result_expires = 3600
# Результаты тасок в backend хранятся 1 час, потом удаляются
# автоматически. Нам не нужно хранить результат пересчёта
# рейтинга вечно — это просто уборка мусора из Redis.

task_default_queue = "default"
task_routes = {
    "products.recalculate_ratings": {"queue": "periodic"},
}
# Разносим периодические таски в отдельную очередь от,
# например, отправки email или обработки заказов.
# Это позволяет масштабировать воркеры независимо:
# отдельный воркер под periodic-очередь не будет
# конкурировать за ресурсы с воркером, обрабатывающим заказы.

beat_schedule = {
    "recalculate-product-ratings": {
        "task": "products.recalculate_ratings",
        "schedule": timedelta(seconds=15),
        "args": (),  # если аргументы статичные; см. ниже про динамику
        "options": {"queue": "periodic"},
    },
}
